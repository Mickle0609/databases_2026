-- =====================================================================
-- Домашнее задание №2, Часть 1. Дополнение схемы (EdTech, вариант 1)
--
-- Скрипт добавляет к схеме из schema_1.sql две новые таблицы:
--   1. categories        — справочник категорий/тем курсов (например,
--                           "Программирование", "Дизайн", "Маркетинг").
--   2. course_categories — таблица-посредник для связи courses <-> categories.
--
-- Зачем это нужно бизнесу: у одного курса может быть несколько категорий
-- (например, курс "Python для аналитиков" относится и к "Программированию",
-- и к "Аналитике данных"), а в одной категории — много курсов. Это
-- классическое отношение "многие-ко-многим" (M:N).
--
-- Как реализовано M:N:
-- В реляционной модели связь M:N нельзя хранить напрямую (ни в courses,
-- ни в categories нет места для "списка" значений без нарушения 1НФ).
-- Поэтому заводится отдельная таблица-посредник course_categories,
-- которая хранит по одной строке на каждую пару "курс-категория".
-- Она имеет составной первичный ключ (course_id, category_id):
--   - это гарантирует, что одна и та же пара не может быть добавлена дважды
--     (сам PK работает как ограничение UNIQUE для пары значений);
--   - и одновременно ускоряет поиск "все категории курса X" (первая часть
--     ключа — course_id).
-- Отдельный индекс на category_id нужен, чтобы так же быстро отвечать на
-- обратный вопрос "все курсы категории Y", не сканируя всю таблицу.
--
-- Что будет при DROP CASCADE:
-- У обоих внешних ключей в course_categories стоит ON DELETE CASCADE.
--   - DROP TABLE courses CASCADE (или удаление конкретного курса)
--     автоматически удалит все строки course_categories, которые на
--     этот курс ссылались, — "осиротевших" связей не останется, но сами
--     категории (справочник) не пострадают.
--   - Аналогично DROP TABLE categories CASCADE (или удаление категории)
--     удалит только связи с этой категорией в course_categories, а сами
--     курсы останутся — просто у них станет на одну категорию меньше.
-- Таким образом course_categories — единственная таблица, которая теряет
-- данные при каскадном удалении; courses и categories как самостоятельные
-- сущности каскадом не затрагиваются.
-- =====================================================================

DROP TABLE IF EXISTS course_categories CASCADE;
DROP TABLE IF EXISTS categories CASCADE;


-- ---------------------------------------------------------------------
-- Таблица 1 (новая). categories — справочник категорий/тем курсов.
-- ---------------------------------------------------------------------
CREATE TABLE categories (
    id          SERIAL PRIMARY KEY,
    name        VARCHAR(100) NOT NULL UNIQUE,  -- название категории, не повторяется
    description TEXT
);


-- ---------------------------------------------------------------------
-- Таблица 2 (новая). course_categories — таблица-посредник M:N между
-- courses и categories. Составной PK одновременно служит и ограничением
-- целостности (запрет дублей), и индексом для поиска по course_id.
-- ---------------------------------------------------------------------
CREATE TABLE course_categories (
    course_id   INTEGER NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
    category_id INTEGER NOT NULL REFERENCES categories(id) ON DELETE CASCADE,
    PRIMARY KEY (course_id, category_id)
);

-- Индекс для обратного поиска "все курсы данной категории" —
-- без него пришлось бы сканировать всю таблицу course_categories.
CREATE INDEX idx_course_categories_category_id ON course_categories(category_id);


-- =====================================================================
-- Дополнительные индексы для СУЩЕСТВУЮЩИХ таблиц из ДЗ №1.
--
-- В ДЗ №1 типовыми частыми запросами были:
--   - «все уроки курса по порядку»               -> lessons(course_id, order_number)
--   - «все отзывы курса и его средний рейтинг»    -> reviews(course_id, rating)
--   - «все выплаты преподавателю за месяц»        -> payouts(teacher_id, pay_month)
--   - «ещё не выплаченные выплаты»                -> payouts(paid_at) — частичный индекс
--   - «завершённые записи на курс»                -> enrollments(course_id, status)
-- FK-колонки этих таблиц уже проиндексированы в schema_1.sql, но для
-- перечисленных запросов одного индекса на FK недостаточно: базе всё
-- равно пришлось бы досортировывать или дофильтровывать строки вручную.
-- Составные и частичные индексы ниже позволяют СУБД ответить на такие
-- запросы, используя только индекс (Index Scan), без полного скана таблицы.
-- =====================================================================

-- «Все уроки курса, в правильном порядке» — index-only по (course_id, order_number)
-- вместо Index Scan + сортировки в памяти.
CREATE INDEX idx_lessons_course_order ON lessons(course_id, order_number);

-- «Отзывы курса» + быстрый расчёт среднего рейтинга без сортировки отдельно по rating.
CREATE INDEX idx_reviews_course_rating ON reviews(course_id, rating);

-- «Выплаты преподавателю за конкретный месяц».
CREATE INDEX idx_payouts_teacher_month ON payouts(teacher_id, pay_month);

-- «Ещё не выплаченные выплаты» — частичный индекс: строится только по
-- строкам с paid_at IS NULL, поэтому он маленький и быстрый именно для
-- этого частого административного запроса.
CREATE INDEX idx_payouts_unpaid ON payouts(teacher_id) WHERE paid_at IS NULL;

-- «Завершённые записи на курс» (например, чтобы посчитать процент
-- завершения курса).
CREATE INDEX idx_enrollments_course_status ON enrollments(course_id, status);
